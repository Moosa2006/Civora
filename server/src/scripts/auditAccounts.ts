import { prisma } from '../lib/prisma.js';

async function audit() {
  const allUsers = await prisma.user.findMany({
    include: {
      _count: {
        select: {
          submittedComplaints: true,
          assignedComplaints: true,
          submittedBids: true,
          auditEvents: true,
          uploadedDocuments: true,
          sentComplaintMessages: true,
          submittedProposals: true,
          pollVotes: true,
          createdTenders: true,
        },
      },
      contractor: {
        select: {
          id: true,
          name: true,
          registrationNumber: true,
        },
      },
    },
    orderBy: { createdAt: 'asc' },
  });

  const categories: Record<string, any[]> = {
    testExampleTest: [], // @example.test
    testAutoGenerated: [], // newcitizen_, hacker_, onboard_, promote_, rej_, supervisor.179...
    seedAccounts: [], // aarav, rahul, priya, rajesh, sunita, meera
    otherAccounts: [],
  };

  for (const u of allUsers) {
    const summary = {
      id: u.id,
      email: u.email,
      name: u.name,
      role: u.role,
      status: u.accountStatus,
      createdAt: u.createdAt,
      contractor: u.contractor?.name,
      counts: u._count,
    };

    if (u.email.endsWith('@example.test')) {
      categories.testExampleTest.push(summary);
    } else if (
      u.email.includes('_179') ||
      u.email.includes('.179') ||
      u.email.endsWith('@test.local') ||
      u.email.startsWith('rej_')
    ) {
      categories.testAutoGenerated.push(summary);
    } else if (
      [
        'aarav.sharma@example.com',
        'priya.patel@example.com',
        'rahul.verma@example.com',
        'rajesh.kumar@example.com',
        'sunita.rao@example.com',
        'admin.meera@civora.local',
      ].includes(u.email)
    ) {
      categories.seedAccounts.push(summary);
    } else {
      categories.otherAccounts.push(summary);
    }
  }

  console.log('=== ACCOUNT AUDIT SUMMARY ===');
  console.log(`@example.test accounts: ${categories.testExampleTest.length}`);
  console.log(`Auto-generated test run accounts: ${categories.testAutoGenerated.length}`);
  console.log(`Base platform/seed accounts: ${categories.seedAccounts.length}`);
  console.log(`Other accounts: ${categories.otherAccounts.length}`);

  console.log('\n--- Details of @example.test ---');
  console.log(JSON.stringify(categories.testExampleTest, null, 2));

  console.log('\n--- Details of Other Accounts ---');
  console.log(JSON.stringify(categories.otherAccounts, null, 2));

  console.log('\n--- Details of Base Seed Accounts ---');
  console.log(JSON.stringify(categories.seedAccounts, null, 2));

  // Check how many auto-generated accounts have dependencies
  const autoWithDeps = categories.testAutoGenerated.filter(
    (u) =>
      u.counts.submittedComplaints > 0 ||
      u.counts.assignedComplaints > 0 ||
      u.counts.submittedBids > 0 ||
      u.counts.auditEvents > 0 ||
      u.counts.uploadedDocuments > 0
  );
  console.log(`\nAuto-generated accounts with relations: ${autoWithDeps.length}`);
  console.log(JSON.stringify(autoWithDeps, null, 2));
}

audit()
  .catch(console.error)
  .finally(() => prisma.$disconnect());
